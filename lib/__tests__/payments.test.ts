import assert from "node:assert/strict";
import test from "node:test";
import path from "node:path";
import { randomUUID } from "node:crypto";
import { rmSync } from "node:fs";
import { spawn } from "node:child_process";
import { DatabaseSync } from "node:sqlite";
import { NextRequest } from "next/server";
import type { LocalOrder } from "../paid-local/types";
import { PaidLocalStore, getPaidLocalStore } from "../paid-local/store";
import { LocalPaidError } from "../paid-local/guard";
import { signMockNotification, localAdminKey } from "../paid-local/admin-auth";
import { GET, POST } from "../../app/api/local-paid/[[...path]]/route";

const code = (name: string) => (e: unknown) => e instanceof LocalPaidError && e.code === name;
test("V3 fixed-price purchases, refunds, admin and ownership", async t => {
  const saved = { ...process.env };
  const file = path.join(process.cwd(), ".local-paid", `payments-${randomUUID()}.sqlite`);
  Object.assign(process.env, { NODE_ENV: "test", PAID_LOCAL_MODE: "1", PAID_LOCAL_MODEL: "mock", PAID_LOCAL_DB: file, NEXT_PUBLIC_SUPABASE_URL: "http://127.0.0.1:9", SUPABASE_SERVICE_ROLE_KEY: "", DEEPSEEK_API_KEY: "" });
  let now = Date.now(); let store = new PaidLocalStore(file, () => now);
  const user = store.login("new").userId; const other = store.login("other").userId;
  const db = new DatabaseSync(file);
  const create = (packageId = "five", account = user, channel = "wechat") => { now += 61000; return store.payments.create(account, { packageId, channel, requestKey: randomUUID() }); };
  try {
    await t.test("catalog charges the same fixed integer-cent prices before and after purchase", () => {
      assert.deepEqual(store.payments.catalog(user).packages.map(x => x.amountCents), [499, 1499, 2499]);
      assert.ok(store.payments.catalog(user).packages.every(x => !x.firstPurchase && x.promotionVersion === null));
      const requestKey = randomUUID(); const first = store.payments.create(user, { packageId: "five", channel: "wechat", requestKey });
      assert.equal(first.amountCents, 1499); assert.equal(first.currency, "CNY");
      assert.equal(store.payments.create(user, { packageId: "five", channel: "wechat", requestKey }).id, first.id);
      assert.equal(first.promotionVersion, null);
      assert.throws(() => create("ten"), code("OPEN_ORDER"));
      assert.throws(() => store.payments.create(user, { packageId: "ten", channel: "wechat", requestKey }), code("REQUEST_CONFLICT"));
      store.payments.cancel(user, first.id);
      assert.equal(store.payments.catalog(user).firstPurchaseEligible, false);
      const failed = create(); store.payments.simulate(user, failed.id, "failed");
      assert.equal(store.payments.order(user, failed.id).state, "failed");
      assert.equal(store.payments.catalog(user).firstPurchaseEligible, false);
      const expired = create(); now += 16 * 60000;
      assert.equal(store.payments.order(user, expired.id).state, "expired");
      assert.equal(store.payments.catalog(user).firstPurchaseEligible, false);
    });
    await t.test("delayed settlement survives restart and repeated events grant once", () => {
      const order = create("ten", user, "waffo"); const before = store.overview(user).balance.available;
      assert.equal(store.payments.simulate(user, order.id, "delay").state, "processing");
      assert.equal(store.overview(user).balance.available, before);
      assert.equal(store.payments.order(user, order.id).state, "processing");
      assert.throws(() => store.payments.cancel(user, order.id), code("PAYMENT_PROCESSING"));
      store.close(); store = new PaidLocalStore(file, () => now); now += 15001;
      assert.equal(store.payments.order(user, order.id).state, "paid");
      store.payments.simulate(user, order.id, "duplicate");
      assert.equal(store.overview(user).balance.available, before + 10);
      assert.deepEqual(store.payments.catalog(user).packages.map(x => x.amountCents), [499, 1499, 2499]);
      store.login("new"); assert.equal(store.payments.catalog(user).firstPurchaseEligible, false);
      const next = create("single"); assert.equal(next.amountCents, 499); store.payments.cancel(user, next.id);
    });
    await t.test("missing, forged and mismatching payment evidence never grant credits", () => {
      const order = create("single", other); const before = store.overview(other).balance.available;
      const payload = JSON.stringify({ orderId: order.id, transactionId: "forged", channel: "wechat", amountCents: 499, currency: "CNY", status: "success" });
      assert.throws(() => store.payments.notify(payload, "0".repeat(64)), code("INVALID_SIGNATURE"));
      assert.throws(() => store.payments.notify(payload, signMockNotification(payload)), code("UNVERIFIED_PAYMENT"));
      assert.throws(() => store.payments.reconcile("local-admin", order.id, randomUUID(), "核查"), code("PAYMENT_UNVERIFIED"));
      assert.equal(store.payments.simulate(other, order.id, "bad_amount").state, "review");
      assert.equal(store.overview(other).balance.available, before);
      assert.throws(() => store.payments.reconcile("local-admin", order.id, randomUUID(), "核查"), code("PAYMENT_UNVERIFIED"));
      const refund = store.payments.requestRefund(other, order.id, randomUUID(), "金额异常退回");
      assert.equal(refund.refunds[0].amountCents, 500);
      store.payments.completeRefund("local-admin", refund.refunds[0].id, true, randomUUID(), "模拟渠道已退回");
      assert.equal(store.overview(other).balance.available, before);
    });
    await t.test("paid-but-unfulfilled orders are reissued once; compensation is separate and audited", () => {
      const order = create("five", other); const before = store.overview(other).balance.available;
      assert.equal(store.payments.simulate(other, order.id, "unfulfilled").fulfillment, "none");
      assert.equal(store.overview(other).balance.available, before);
      const key = randomUUID(); store.payments.reconcile("local-admin", order.id, key, "补发已核实订单");
      store.payments.reconcile("local-admin", order.id, key, "补发已核实订单");
      store.payments.reconcile("local-admin", order.id, randomUUID(), "再次核查");
      assert.equal(store.overview(other).balance.available, before + 5);
      assert.throws(() => store.payments.reconcile("local-admin", order.id, key, "另一操作"), code("REQUEST_CONFLICT"));
      const comp = randomUUID(); store.payments.compensate("local-admin", other, 2, comp, "服务补偿"); store.payments.compensate("local-admin", other, 2, comp, "服务补偿");
      assert.equal(store.overview(other).balance.available, before + 7);
      assert.throws(() => store.payments.compensate("local-admin", other, 3, comp, "服务补偿"), code("REQUEST_CONFLICT"));
      assert.throws(() => store.payments.compensate("local-admin", other, 2, randomUUID(), ""), code("REASON_REQUIRED"));
    });
    await t.test("refund holds only its purchase and failure restores credits without changing prices", () => {
      const order = create("five"); store.payments.simulate(user, order.id, "success");
      const batch = db.prepare("SELECT batch_id FROM local_orders WHERE id=?").get(order.id)!;
      // Emulate one previously completed reading from this particular purchase.
      db.prepare("UPDATE credit_batches SET consumed=1 WHERE id=?").run(batch.batch_id!);
      const before = store.overview(user).balance.available;
      const requestKey = randomUUID(); const refund = store.payments.requestRefund(user, order.id, requestKey, "退还未使用部分");
      assert.equal(refund.refunds[0].credits, 4); assert.equal(refund.refunds[0].amountCents, 1199);
      assert.equal(store.overview(user).balance.available, before - 4);
      assert.equal(store.payments.requestRefund(user, order.id, requestKey, "退还未使用部分").refunds.length, 1);
      store.payments.completeRefund("local-admin", refund.refunds[0].id, false, randomUUID(), "模拟退款失败");
      assert.equal(store.overview(user).balance.available, before);
      const again = store.payments.requestRefund(user, order.id, randomUUID(), "再次退款");
      const completed = store.payments.completeRefund("local-admin", again.refunds[0].id, true, randomUUID(), "模拟退款成功");
      assert.equal(completed.state, "partially_refunded"); assert.equal(store.overview(user).balance.available, before - 4);
      store.payments.completeRefund("local-admin", again.refunds[0].id, true, randomUUID(), "重复确认");
      assert.equal(store.overview(user).balance.available, before - 4);
      assert.equal(store.payments.catalog(user).firstPurchaseEligible, false);
      assert.throws(() => store.payments.requestRefund(user, order.id, randomUUID(), "已无可退花瓣"), code("NO_REFUNDABLE_CREDITS"));
      const reserved = create("single"); store.payments.simulate(user, reserved.id, "success");
      db.prepare("UPDATE credit_batches SET reserved=1 WHERE id=(SELECT batch_id FROM local_orders WHERE id=?)").run(reserved.id);
      assert.throws(() => store.payments.requestRefund(user, reserved.id, randomUUID(), "解读中退款"), code("CREDITS_RESERVED"));
    });
    await t.test("payment races across processes still create one receipt, grant and first redemption", async () => {
      const order = create("ten", other); const before = store.overview(other).balance.available;
      const results = await Promise.all(Array.from({ length: 6 }, () => new Promise<string>((resolve, reject) => {
        const worker = spawn(process.execPath, ["scripts/payment-worker.cjs", other, order.id], { cwd: process.cwd(), env: process.env, windowsHide: true });
        let out = "", err = ""; worker.stdout.on("data", d => out += d); worker.stderr.on("data", d => err += d);
        worker.on("error", reject); worker.on("exit", n => n ? reject(new Error(err)) : resolve(out.trim()));
      })));
      assert.deepEqual(new Set(results), new Set(["granted"])); assert.equal(store.overview(other).balance.available, before + 10);
      assert.equal(db.prepare("SELECT count(*) n FROM credit_batches WHERE event_key=?").get(`purchase:v3:${order.id}`)?.n, 1);
    });
    await t.test("owned reading context and fixed prices are retained after a full refund", () => {
      const legacy = store.login("legacy").userId;
      const project = store.saveProject(legacy, { title: "付款后继续", background: "" });
      const reading = store.draw(legacy, { projectId: project.id, question: "我接下来如何推进这个计划？", spread: "three_card", requestKey: randomUUID() });
      assert.throws(() => store.payments.create(user, { packageId: "single", channel: "wechat", requestKey: randomUUID(), readingId: reading.id }), code("NOT_FOUND"));
      const order = store.payments.create(legacy, { packageId: "single", channel: "waffo", requestKey: randomUUID(), readingId: reading.id });
      assert.equal(order.amountCents, 499); assert.equal(order.readingId, reading.id);
      assert.equal(order.returnPath, `/deep/project/${project.id}?view=history&reading=${reading.id}#reading-${reading.id}`);
      const before = store.overview(legacy).balance.available; store.payments.simulate(legacy, order.id, "success");
      const refund = store.payments.requestRefund(legacy, order.id, randomUUID(), "测试固定价格全退");
      assert.equal(refund.refunds[0].amountCents, 499);
      const done = store.payments.completeRefund("local-admin", refund.refunds[0].id, true, randomUUID(), "渠道退款成功");
      assert.equal(done.state, "refunded"); assert.equal(store.overview(legacy).balance.available, before);
      assert.equal(store.payments.catalog(legacy).firstPurchaseEligible, false);
    });
    await t.test("API enforces account ownership, CSRF and independent admin authentication", async () => {
      const api = getPaidLocalStore(); const session = api.login("legacy"); const otherSession = api.login("other");
      const request = (action: string, body?: object, cookie = `flora_paid_local_session=${session.token}`) => new NextRequest(`http://127.0.0.1:3100/api/local-paid/${action}`, { method: body ? "POST" : "GET", headers: { host: "127.0.0.1:3100", origin: "http://127.0.0.1:3100", "x-local-paid": "1", "content-type": "application/json", cookie }, ...(body ? { body: JSON.stringify(body) } : {}) });
      const post = (action: string, body: object, cookie?: string) => POST(request(action, body, cookie), { params: Promise.resolve({ path: action.split("/") }) });
      const get = (action: string, cookie?: string) => GET(request(action, undefined, cookie), { params: Promise.resolve({ path: action.split("/") }) });
      const response = await post("orders", { packageId: "single", channel: "wechat", requestKey: randomUUID(), amountCents: 1, admin: true }); const order = await response.json() as LocalOrder;
      assert.equal(response.status, 200); assert.equal(order.amountCents, 499);
      assert.equal((await get(`orders/${order.id}`, `flora_paid_local_session=${otherSession.token}`)).status, 404);
      assert.equal((await post("payment-simulate", { orderId: order.id, mode: "success" }, `flora_paid_local_session=${otherSession.token}`)).status, 404);
      assert.equal((await get("admin")).status, 401);
      assert.equal((await get("xianyu", "")).status,401);
      const fixtureProduct={packageId:"single",firstPurchase:false,goodsNo:"flora-single-regular",sellerIdentity:"test-seller",productId:"123456789",itemId:"659437081448"};
      const xianyu=api.xianyu.prepare(session.userId,"single",randomUUID(),[fixtureProduct]);
      assert.equal((await get(`xianyu/orders/${xianyu.id}`,`flora_paid_local_session=${otherSession.token}`)).status,404);
      const own=await (await get(`xianyu/orders/${xianyu.id}`)).json() as {accountCode:string};
      assert.equal(own.accountCode,xianyu.accountCode);
      const publicCatalog=await (await get("xianyu")).json() as Record<string,unknown>;
      assert.equal("credentials" in publicCatalog,false);
      const forgedXianyu=request("xianyu/checkout",{packageId:"single",requestKey:randomUUID()});forgedXianyu.headers.set("origin","https://evil.invalid");
      assert.equal((await POST(forgedXianyu,{params: Promise.resolve({path:["xianyu","checkout"]})})).status,403);
      assert.equal((await post("admin/compensate", { userId: session.userId, count: 10, reason: "hack", requestKey: randomUUID() })).status, 401);
      const qr = await (await get(`orders/${order.id}/qr`)).json() as {mode:string;dataUrl:string}; assert.equal(qr.mode, "simulation"); assert.match(qr.dataUrl, /^data:image\/png;base64,/);
      const login = await post("admin/session", { key: localAdminKey() }); assert.equal(login.status, 200);
      const admin = login.cookies.get("flora_paid_local_admin")!.value; const cookie = `flora_paid_local_admin=${admin}`;
      assert.match(login.headers.get("set-cookie")!, /HttpOnly/i);
      assert.equal((await get("admin", cookie)).status, 200);
      const adminOrders=await (await get("admin",cookie)).json() as {xianyuOrders:{accountCode:string}[]};
      assert.ok(adminOrders.xianyuOrders.every(x=>x.accountCode === ""));
      assert.equal((await post("admin/reconcile", { orderId: order.id, reason: "没有付款凭据", requestKey: randomUUID() }, cookie)).status, 409);
      const badOrigin = request("orders", { packageId: "single" }); badOrigin.headers.set("origin", "https://evil.invalid");
      assert.equal((await POST(badOrigin, { params: Promise.resolve({ path: ["orders"] }) })).status, 403);
      await post("admin/logout", {}, cookie); assert.equal((await get("admin", cookie)).status, 401);
      const token = store.payments.adminLogin(localAdminKey()); store.payments.authenticateAdmin(token); now += 7200001; assert.throws(() => store.payments.authenticateAdmin(token), code("ADMIN_UNAUTHORIZED"));
      api.close(); delete (globalThis as {paidLocalStore?:unknown}).paidLocalStore;
    });
  } finally {
    db.close(); store.close(); Object.assign(process.env, saved);
    for (const key of Object.keys(process.env)) if (!(key in saved)) delete process.env[key];
    for (const suffix of ["", "-wal", "-shm"]) rmSync(file + suffix, { force: true });
  }
});
